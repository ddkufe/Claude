// Packs reader/undertone.html (the same page as the web version) into src/readerHtml.js
// so the app can load it into its web view. Run after editing the reader: npm run build:reader
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const page = fs.readFileSync(path.join(root, 'reader', 'undertone.html'), 'utf8');

const html = `<!doctype html>
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<style>
:root{color-scheme:light;box-sizing:border-box;padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}
body{margin:0;padding:0;font:14px -apple-system,BlinkMacSystemFont,sans-serif}
img{max-width:100%}
[hidden]{display:none!important}
</style>
</head>
<body>
${page}
</body>
</html>`;

const out = `// Generated by scripts/build-reader.js from reader/undertone.html. Do not edit by hand.
export const READER_HTML = ${JSON.stringify(html)};
`;
fs.writeFileSync(path.join(root, 'src', 'readerHtml.js'), out);
console.log('Wrote src/readerHtml.js (' + Math.round(out.length / 1024) + ' KB)');
